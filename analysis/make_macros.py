"""Write paper/results_macros.tex: seed-averaged D3 numbers used in the text, so prose never hard-codes results.

\\CRPS<model><stratum><h>, \\MAE.., \\PICP.., \\ECE..  (h: '' = 12-step average, A/B/C = 15/30/60 min)
\\Gain<model><stratum><h> = % CRPS reduction of WARP-Traffic (pooled) relative to <model>.
"""
import os, sys, numpy as np
sys.path.insert(0, os.path.dirname(__file__))
from aggregate import collect

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # holds data_raw, data_proc, results, paper
PAPER = os.path.join(ROOT, "paper")
MODELS = {"clim": "climatology", "gw": "gwnet_gauss", "gwx": "gwnet_gauss+wx", "st": "staeformer_quantile", "da": "deepar",
          "ens": "gwens", "wxp": "gwwxpool", "rmo": "remind_orig", "rm": "remind", "rmw": "remind_wx", "rmp": "remindpool",
          "mem": "wremind", "wr": "wremindpool", "gwc": "gwnet_conformal"}
STRATA = {"All": "all", "Nor": "normal", "Ev": "anyevent", "Heat": "heat", "Rain": "rain", "Smoke": "smoke", "Inc": "incident",
          "Lrain": "lightrain"}
HZ = {"": "avg", "A": "15min", "B": "30min", "C": "60min"}


def main(region="D3"):
    df = collect(region)
    m = df.groupby(["model", "stratum", "horizon"]).mean(numeric_only=True)
    ms = df.groupby(["model", "seed", "stratum", "horizon"]).mean(numeric_only=True)
    seeds = df.groupby("model").seed.agg(lambda x: set(x))
    nseed = df.groupby("model").seed.nunique()
    out = [f"% generated by analysis/make_macros.py ({region})"]

    def get(k, st, hz, met):
        try:
            return float(m.loc[(MODELS[k], st, hz), met])
        except KeyError:
            return np.nan

    def pair(k, j, st, hz):
        # CRPS of k and j averaged over their common seeds only, so seed-0-only baselines are compared like for like
        c = sorted(seeds.get(MODELS[k], set()) & seeds.get(MODELS[j], set()))
        try:
            return tuple(float(np.mean([ms.loc[(MODELS[x], sd, st, hz), "CRPS"] for sd in c])) for x in (k, j)) if c else (np.nan, np.nan)
        except KeyError:
            return np.nan, np.nan

    for k in MODELS:
        for sk, st in STRATA.items():
            for hk, hz in HZ.items():
                for met, d in [("CRPS", 2), ("MAE", 2), ("PICP90", 3), ("ECE", 3)]:
                    v = get(k, st, hz, met)
                    if not np.isnan(v):
                        out.append(f"\\newcommand{{\\{met.replace('90', '')}{k}{sk}{hk}}}{{{v:.{d}f}}}")
                v, ref = pair("wr", k, st, hz)
                if k != "wr" and not np.isnan(v) and not np.isnan(ref):
                    out.append(f"\\newcommand{{\\Gain{k}{sk}{hk}}}{{{100 * (1 - v / ref):.1f}}}")
                v, ref = pair(k, "gw", st, hz)
                if k != "gw" and not np.isnan(v) and not np.isnan(ref):   # % CRPS reduction vs GWNet-G (common seeds)
                    out.append(f"\\newcommand{{\\Rel{k}{sk}{hk}}}{{{100 * (1 - v / ref):.1f}}}")
                if k not in ("wr", "clim"):
                    ref, cl = get(k, st, hz, "CRPS"), get("clim", st, hz, "CRPS")
                    if not np.isnan(ref) and not np.isnan(cl):
                        out.append(f"\\newcommand{{\\Skill{k}{sk}{hk}}}{{{100 * (1 - ref / cl):.1f}}}")
        if MODELS[k] in nseed:
            out.append(f"\\newcommand{{\\Seeds{k}}}{{{int(nseed[MODELS[k]])}}}")
    # implied Cramer distance between pooled experts (Eq. pooldecomp, lambda = 0.5) and the CRPS-optimal weight
    # All on seed 0 (the only seed every pool and ablation has), so every distance in the paper uses one convention.
    # The scores are those of the truncated forecasts, so C is the distance implied by Eq. (pooldecomp), an approximation.
    def get0(model, st, hz):
        try:
            return float(ms.loc[(model, 0, st, hz), "CRPS"])
        except KeyError:
            return np.nan
    pairs = {"wr": ("wremindpool", "wremind", "gwnet_gauss"), "rmp": ("remindpool", "remind", "gwnet_gauss"),
             "wxp": ("gwwxpool", "gwnet_gauss+wx", "gwnet_gauss"), "wxret": ("pool_wremind_wxret", "wremind_wxret", "gwnet_gauss")}
    for pk, (p_, a, b) in pairs.items():
        for sk, st in STRATA.items():
            for hk, hz in HZ.items():
                P, A, B = get0(p_, st, hz), get0(a, st, hz), get0(b, st, hz)
                if np.isnan(P + A + B):
                    continue
                C = 4 * (0.5 * (A + B) - P)
                out.append(f"\\newcommand{{\\Cram{pk}{sk}{hk}}}{{{C:.2f}}}")
                if C > 0 and a != b:
                    out.append(f"\\newcommand{{\\Lopt{pk}{sk}{hk}}}{{{0.5 + (B - A) / (2 * C):.2f}}}")
    for k in ("wr", "gw", "mem"):
        try:
            v = float(m.loc[(MODELS[k], "all", "avg"), "Violation"])
            out.append(f"\\newcommand{{\\Viol{k}}}{{{100 * v:.2f}}}")
        except KeyError:
            pass
    open(os.path.join(PAPER, "results_macros.tex"), "w").write("\n".join(out) + "\n")
    print(len(out), "macros")


if __name__ == "__main__":
    main(*sys.argv[1:])
